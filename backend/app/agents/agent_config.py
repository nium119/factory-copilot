def get_agent_metadata(name: str) -> Dict[str, str]:
    """
    获取指定 Agent 的展示用元数据。

    用于前端渲染（侧边栏列表、消息气泡、协作事件）、系统提示词构建等场景。
    如果 name 不在注册表中，返回带默认值的空壳对象，不会抛异常。

    Args:
        name: Agent 内部标识名，如 "scheduling", "quality"

    Returns:
        {
            "name": "scheduling",
            "display_name": "排产助手",
            "icon": "📋",
            "color": "#0984e3",
            "description": "生产计划排期、产能分析与调度优化",
        }
    """
    info = AGENT_DEFINITIONS.get(name, {})
    return {
        "name": name,
        "display_name": info.get("display_name", name),
        "icon": info.get("icon", "🤖"),
        "color": info.get("color", "#6c5ce7"),
        "description": info.get("description", ""),
    }


def get_all_agent_names(exclude: List[str] = None) -> List[str]:
    """
    获取所有已注册 Agent 的名称列表（按定义顺序）。

    常用于：
      - router.py 遍历匹配用户意图
      - collaborator.py 获取可协作的 Agent 列表
      - init_agents.py 数据库种子初始化

    Args:
        exclude: 需要排除的 Agent 名称列表。
                 例如 exclude=["general"] 排除兜底 Agent。

    Returns:
        按定义顺序排列的 Agent 名称列表，如
        ["general", "scheduling", "quality", "equipment", ...]
    """
    names = list(AGENT_DEFINITIONS.keys())
    if exclude:
        names = [n for n in names if n not in exclude]
    return names
